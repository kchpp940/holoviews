class DisplayExtension:
    """Base class for display extensions.

    Subclasses override *one or more* of the hook methods below.  Each
    hook receives the HoloViews object being rendered and returns
    extension data appropriate to that hook.  Hooks are always called
    with an object; if the extension does not apply to that object it
    should return ``None`` (or an empty collection) so the registry
    moves on to the next extension.

    Hook return contracts:

    * :meth:`get_hover_specs`  →  ``list[HoverSpec]`` or ``None``
    * :meth:`get_hover_fields` →  ``list[str | Dimension | dim()]`` or ``None``
      (convenience; the registry will translate these into HoverSpecs)
    * :meth:`get_panel_specs`  →  ``list[PanelSpec]`` or ``None``
    * :meth:`get_html_panel`   →  ``str`` HTML block (convenience)
    * :meth:`get_text_extras`  →  ``list[(label, value)]`` tuples appended to repr
    * :meth:`get_metadata`     →  ``dict`` of JSON-serialisable metadata

    In addition, :meth:`applies_to` lets subclasses short-circuit for
    unsupported object types (the default is to apply to any object).
    """

    name: str = "unnamed_extension"
    priority: int = 100
    enabled: bool = True
    contexts: DisplayContext = DisplayContext.ALL

    # ------------------------------------------------------------------ hooks

    def applies_to(self, obj: Any) -> bool:
        """Return True if this extension knows how to extend *obj*."""
        return True

    # -- Hover / tooltip --------------------------------------------------

    def get_hover_fields(self, obj: Any) -> Optional[List[Any]]:
        """Return a list of hover field specs (strings, Dimension, dim()).

        This is a convenience entry point.  Extensions that need fine
        control (custom labels, per-field formatters, pre-computed value
        arrays) should override :meth:`get_hover_specs` instead.
        """
        return None

    def get_hover_specs(self, obj: Any) -> Optional[List[HoverSpec]]:
        """Return the canonical list of HoverSpec objects for *obj*.

        The default implementation turns the output of
        :meth:`get_hover_fields` into HoverSpecs; subclasses should
        override this directly if they already have richer information.
        """
        fields = self.get_hover_fields(obj)
        if not fields:
            return None
        specs: List[HoverSpec] = []
        for f in fields:
            name = self._field_name(f, obj)
            specs.append(HoverSpec(name=name))
        return specs

    # -- Panels (side panel / HTML repr) ----------------------------------

    def get_html_panel(self, obj: Any) -> Optional[str]:
        """Return a raw HTML string to include inline next to the plot.

        Convenience alternative to :meth:`get_panel_specs`.
        """
        return None

    def get_panel_specs(self, obj: Any) -> Optional[List[PanelSpec]]:
        """Return the canonical list of PanelSpec objects for *obj*."""
        html_panel = self.get_html_panel(obj)
        if html_panel is None:
            return None
        return [PanelSpec(html_content=html_panel, title=self.name)]

    # -- Text repr --------------------------------------------------------

    def get_text_extras(self, obj: Any) -> Optional[List[Tuple[str, Any]]]:
        """Return ``[(label, value)]`` tuples to append to the text repr."""
        return None

    # -- Metadata ---------------------------------------------------------

    def get_metadata(self, obj: Any) -> Optional[Dict[str, Any]]:
        """Return a JSON-serialisable dict of extra metadata."""
        return None

    # ------------------------------------------------------------------ utils

    @staticmethod
    def _field_name(field: Any, obj: Any) -> str:
        from .dimension import Dimension
        from ..util.transform import dim as _dim

        if isinstance(field, _dim):
            if len(field.ops) == 0:
                return DisplayExtension._field_name(field.dimension, obj)
            return str(field)
        if isinstance(field, Dimension):
            return field.name
        if isinstance(field, str):
            return field
        return str(field)


