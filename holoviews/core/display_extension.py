class DisplayContext(enum.Flag):
    """Display contexts in which an extension may contribute content."""

    NONE = 0
    HOVER_TOOLTIP = enum.auto()
    HTML_REPR = enum.auto()
    SIDE_PANEL = enum.auto()
    TEXT_REPR = enum.auto()
    METADATA = enum.auto()
    ALL = HOVER_TOOLTIP | HTML_REPR | SIDE_PANEL | TEXT_REPR | METADATA


@dataclass
class HoverSpec:
    """Normalised specification of a single hover/tooltip entry.

    A list of these is produced by :meth:`DisplayExtension.get_hover_specs`
    and consumed by the backends when building tooltip widgets.
    """

    name: str
    label: Optional[str] = None
    formatter: Optional[Union[str, Callable[[Any], str]]] = None
    values: Optional[Any] = None
    enabled: bool = True


@dataclass
class PanelSpec:
    """Normalised specification of an auxiliary information panel.

    Produced by :meth:`DisplayExtension.get_panel_specs` and used to
    render side panels (in Bokeh / Panel) or inline HTML blocks
    (notebook repr).
    """

    title: Optional[str] = None
    content: Optional[Any] = None
    html_content: Optional[str] = None
    position: str = "right"
    priority: int = 0
    extra: Dict[str, Any] = field(default_factory=dict)
    enabled: bool = True


@dataclass
class DisplayPayload:
    """Unified container for all display-related content generated by
    the extension registry.

    A single :class:`DisplayPayload` is produced from an object by
    :func:`get_display_payload` and consumed by the renderer, display
    hooks, and backends.  This ensures that the same aggregated
    information is used for hover tooltips, HTML repr, side panels,
    text repr and metadata everywhere the object is rendered.
    """

    hover_specs: List[HoverSpec] = field(default_factory=list)
    hover_data: Dict[str, Any] = field(default_factory=dict)
    hover_tooltips: List[Tuple[str, str]] = field(default_factory=list)
    panel_specs: List[PanelSpec] = field(default_factory=list)
    html_panels: List[str] = field(default_factory=list)
    side_panels: List[PanelSpec] = field(default_factory=list)
    text_extras: List[Tuple[str, Any]] = field(default_factory=list)
    metadata: Dict[str, Any] = field(default_factory=dict)
    source_obj: Optional[Any] = None

    @property
    def has_hover(self) -> bool:
        return bool(self.hover_specs)

    @property
    def has_panels(self) -> bool:
        return bool(self.html_panels)

    @property
    def has_text_extras(self) -> bool:
        return bool(self.text_extras)

    @property
    def has_metadata(self) -> bool:
        return bool(self.metadata)

    @property
    def has_any(self) -> bool:
        return self.has_hover or self.has_panels or self.has_text_extras or self.has_metadata

    def as_text_suffix(self) -> str:
        """Return a string suffix suitable for appending to ``__repr__``."""
        if not self.text_extras:
            return ""
        lines = []
        for label, value in self.text_extras:
            lines.append(f"   |_{label}: {value!r}")
        return "\n" + "\n".join(lines)

    def wrap_html(self, main_html: str) -> str:
        """Wrap *main_html* with side panels in a flex layout."""
        if not self.html_panels:
            return main_html
        panels_html = "".join(self.html_panels)
        return (
            '<div class="hv-display-wrapper" style="display:flex;flex-wrap:wrap;'
            'align-items:flex-start;gap:12px;">'
            '<div class="hv-main-plot" style="flex:1 1 auto;min-width:0;">'
            + main_html
            + "</div>"
            + '<div class="hv-side-panels" style="flex:0 1 320px;max-width:100%;">'
            + panels_html
            + "</div>"
            + "</div>"
        )

    def update_mime_metadata(self, metadata: Dict[str, Any], mime_key: str) -> None:
        """Update a MIME metadata dict in-place with this payload's metadata."""
        if not self.metadata:
            return
        hv_exec_meta = metadata.setdefault(mime_key, {})
        hv_exec_meta["hv_metadata"] = dict(self.metadata)


