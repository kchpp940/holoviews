class DisplayExtensionRegistry:
    """Ordered registry of :class:`DisplayExtension` instances.

    The registry owns the :func:`apply_extensions` helper used by the
    rest of HoloViews to collect extension contributions.  Extensions
    are kept in insertion order (subject to ``priority``) and may be
    enabled / disabled at runtime.

    There is one process-wide registry returned by :func:`get_registry`.
    """

    def __init__(self) -> None:
        self._extensions: "OrderedDict[str, DisplayExtension]" = OrderedDict()
        self._register_defaults()

    # ------------------------------------------------------------------ API

    def register(self, extension: DisplayExtension) -> None:
        """Register an extension (replaces any previous with same name)."""
        if not isinstance(extension, DisplayExtension):
            raise TypeError(
                f"Expected DisplayExtension instance, got {type(extension).__name__}"
            )
        self._extensions[extension.name] = extension
        self._sort()

    def unregister(self, name: str) -> Optional[DisplayExtension]:
        return self._extensions.pop(name, None)

    def get(self, name: str) -> Optional[DisplayExtension]:
        return self._extensions.get(name)

    def list(self) -> List[DisplayExtension]:
        return list(self._extensions.values())

    def clear(self) -> None:
        self._extensions.clear()
        self._register_defaults()

    # ------------------------------------------------------------ aggregation

    def apply(
        self,
        obj: Any,
        hook: str,
        context: DisplayContext = DisplayContext.ALL,
    ) -> List[Any]:
        """Run *hook* on every applicable enabled extension.

        Returns a flat list of the non-``None`` results.

        Parameters
        ----------
        obj:
            The HoloViews object being rendered.
        hook:
            Name of a method on :class:`DisplayExtension`, e.g.
            ``"get_hover_specs"``, ``"get_metadata"``.
        context:
            Only extensions whose ``contexts`` flag intersects this
            value are called.
        """
        results: List[Any] = []
        for ext in self._extensions.values():
            if not ext.enabled:
                continue
            if not (ext.contexts & context):
                continue
            if not ext.applies_to(obj):
                continue
            method = getattr(ext, hook, None)
            if method is None:
                continue
            try:
                result = method(obj)
            except Exception:  # noqa: BLE001 - never let a bad extension break rendering
                result = None
            if result is None:
                continue
            if isinstance(result, list):
                results.extend(result)
            else:
                results.append(result)
        return results

    # ------------------------------------------------------------------ utils

    def _register_defaults(self) -> None:
        self._extensions[DimensionedHoverExtension.name] = DimensionedHoverExtension()
        self._extensions[DynamicMapExtension.name] = DynamicMapExtension()
        self._extensions[OperationContextExtension.name] = OperationContextExtension()
        self._extensions[MetadataExtension.name] = MetadataExtension()
        self._sort()

    def _sort(self) -> None:
        self._extensions = OrderedDict(
            sorted(self._extensions.items(), key=lambda kv: (-kv[1].priority, kv[0]))
        )


# ---------------------------------------------------------------------------
# Module-level convenience API
# ---------------------------------------------------------------------------


_global_registry: Optional[DisplayExtensionRegistry] = None


def get_registry() -> DisplayExtensionRegistry:
    """Return the process-wide :class:`DisplayExtensionRegistry`."""
    global _global_registry
    if _global_registry is None:
        _global_registry = DisplayExtensionRegistry()
    return _global_registry


def register_extension(extension: DisplayExtension) -> None:
    get_registry().register(extension)


def unregister_extension(name: str) -> Optional[DisplayExtension]:
    return get_registry().unregister(name)


def apply_extensions(obj: Any, hook: str, context: DisplayContext = DisplayContext.ALL) -> List[Any]:
    return get_registry().apply(obj, hook, context)


# ----------------------------------------------------------- specialised getters


def get_hover_fields(obj: Any) -> List[HoverSpec]:
    """Aggregate HoverSpecs from every extension that applies to *obj*.

    This is the single entry point used by the backends when building
    hover tooltips.  It is the successor to the ad-hoc
    ``element._get_hover_fields`` / ``plot._hover_opts`` combination.
    """
    specs = apply_extensions(obj, "get_hover_specs", DisplayContext.HOVER_TOOLTIP)
    dedup: "OrderedDict[str, HoverSpec]" = OrderedDict()
    for spec in specs:
        if not isinstance(spec, HoverSpec):
            continue
        if not spec.enabled:
            continue
        if spec.name in dedup and spec.label:
            dedup[spec.name].label = spec.label or dedup[spec.name].label
            dedup[spec.name].formatter = spec.formatter or dedup[spec.name].formatter
            dedup[spec.name].values = spec.values if spec.values is not None else dedup[spec.name].values
        else:
            dedup[spec.name] = spec
    return list(dedup.values())


def get_hover_field_names(obj: Any) -> List[str]:
    return [s.name for s in get_hover_fields(obj)]


def get_hover_data(obj: Any) -> Dict[str, Any]:
    """Return the aggregated ``{field_name: values}`` dict for *obj*.

    Falls back to pulling values directly from the element when an
    extension declared a HoverSpec without a ``values`` array.
    """
    data: Dict[str, Any] = {}
    from . import util
    from .dimension import Dimensioned

    is_dim = isinstance(obj, Dimensioned)
    for spec in get_hover_fields(obj):
        if spec.values is not None:
            data[util.dimension_sanitizer(spec.name)] = spec.values
            continue
        if not is_dim:
            continue
        try:
            dim = obj.get_dimension(spec.name)
            if dim is not None:
                data[util.dimension_sanitizer(spec.name)] = obj.dimension_values(dim)
            else:
                from ..util.transform import dim as _dim
                data[util.dimension_sanitizer(spec.name)] = _dim(spec.name).apply(obj)
        except (KeyError, ValueError):
            pass
    return data


def get_hover_tooltips(obj: Any) -> List[Tuple[str, str]]:
    """Return a list of ``(label, value_ref)`` tuples suitable for use
    directly as Bokeh ``tooltips`` or as the basis for other backends.
    """
    from . import util

    tooltips: List[Tuple[str, str]] = []
    for spec in get_hover_fields(obj):
        label = spec.label or spec.name
        safe = util.dimension_sanitizer(spec.name)
        tooltips.append((label, f"@{{{safe}}}"))
    return tooltips


def get_panel_specs(obj: Any, position: Optional[str] = None) -> List[PanelSpec]:
    specs = apply_extensions(obj, "get_panel_specs", DisplayContext.SIDE_PANEL | DisplayContext.HTML_REPR)
    result = []
    for spec in specs:
        if not isinstance(spec, PanelSpec):
            continue
        if not spec.enabled:
            continue
        if position is not None and spec.position != position:
            continue
        result.append(spec)
    result.sort(key=lambda s: -s.priority)
    return result


def get_html_panels(obj: Any) -> List[str]:
    """Return all HTML panels as a list of strings, in priority order."""
    panels: List[str] = []
    for spec in get_panel_specs(obj):
        if spec.html_content:
            panels.append(spec.html_content)
        elif spec.content is not None:
            try:
                panels.append(html.escape(str(spec.content)))
            except Exception:  # noqa: BLE001
                pass
    return panels


def get_side_panels(obj: Any, position: str = "right") -> List[PanelSpec]:
    return get_panel_specs(obj, position=position)


def get_text_extras(obj: Any) -> List[Tuple[str, Any]]:
    """Aggregate text extras from all extensions for *obj*.

    Each extension may return a list of ``(label, value)`` tuples,
    which are flattened by :meth:`DisplayExtensionRegistry.apply`
    before being returned here.
    """
    extras: List[Tuple[str, Any]] = []
    for item in apply_extensions(obj, "get_text_extras", DisplayContext.TEXT_REPR):
        extras.append(item)
    return extras


def get_metadata(obj: Any) -> Dict[str, Any]:
    meta: Dict[str, Any] = {}
    for batch in apply_extensions(obj, "get_metadata", DisplayContext.METADATA):
        if isinstance(batch, dict):
            meta.update(batch)
    return meta


def get_display_payload(obj: Any) -> DisplayPayload:
    """Build a single :class:`DisplayPayload` containing every piece of
    display-extension content for *obj*.

    This is the primary entry point used by the renderer and display
    hooks.  It calls each getter once and stores the aggregated
    results, ensuring all rendering paths consume the exact same data.

    Parameters
    ----------
    obj:
        The HoloViews object being rendered.

    Returns
    -------
    DisplayPayload
        Populated with hover specs/data, panels, text extras and
        metadata aggregated from every registered extension.
    """
    return DisplayPayload(
        hover_specs=get_hover_fields(obj),
        hover_data=get_hover_data(obj),
        hover_tooltips=get_hover_tooltips(obj),
        panel_specs=get_panel_specs(obj),
        html_panels=get_html_panels(obj),
        side_panels=get_side_panels(obj),
        text_extras=get_text_extras(obj),
        metadata=get_metadata(obj),
        source_obj=obj,
    )


