"""Unified display extension framework for HoloViews.

This module provides a single, consistent mechanism for injecting
auxiliary display content into all rendering paths:

- Notebook HTML repr  (``_repr_html_`` / IPython display hooks)
- Hover tooltips      (Bokeh HoverTool, matplotlib format_coord, Plotly hovertemplate)
- Side info panels    (Bokeh sidebar/extra panels, Panel layouts)
- Python repr         (``__repr__`` / PrettyPrinter)
- Generic metadata    (carried through all channels above)

Previously these concerns were addressed ad-hoc in
``ipython/display_hooks.py``, ``plotting/renderer.py``, each backend's
``element.py`` and the core ``Dimensioned`` class.  The extension
registry defined below centralises them so that any piece of extra
information (DynamicMap operation info, operation debug output, user
metadata, ...) only has to be registered once to appear consistently
everywhere the object is rendered.

Typical usage::

    from holoviews.core.display_extension import (
        DisplayExtension, register_extension, apply_extensions
    )

    class MyExtension(DisplayExtension):
        name = "my_ext"

        def get_hover_fields(self, obj):
            return ["custom_field"]

        def get_html_panel(self, obj):
            return "<div>Custom info</div>"

    register_extension(MyExtension())

    # Internally, rendering code consumes extensions via:
    panels = apply_extensions(obj, "html_panel")   # list of HTML strings
    fields = apply_extensions(obj, "hover_fields") # aggregated field list

See the docstring of :class:`DisplayExtension` for the full set of
hooks a subclass may override.
"""

from __future__ import annotations

